public class NewProduct
{
    int id = 0;
    string title = "";
    string icon = "";
    string type = "";
    string link = "";

    public int Id
    {
        get => id;
        set => id = value;
    }
    public string Title
    {
        get => title;
        set => title = value;
    }
    public string Icon
    {
        get => icon;
        set => icon = value;
    }
    public string Type
    {
        get => type;
        set => type = value;
    }
    public string Link
    {
        get => link;
        set => link = value;
    }
}
